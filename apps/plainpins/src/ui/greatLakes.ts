/** Rings wound the way a GeoJSON polygon's outside is (so each is the lake, not everything but the lake). */
export const GREAT_LAKES: Ring[] = [MICH, SUPERIOR, HURON, ERIE, ONTARIO].map((ring) => {
  const closed: Ring = [...ring, ring[0]];
  // Signed area on the plane: positive means counter-clockwise in lng/lat.
  let area = 0;
  for (let i = 0; i < closed.length - 1; i++) area += closed[i][0] * closed[i + 1][1] - closed[i + 1][0] * closed[i][1];
  // d3 treats a clockwise ring (as seen on the sphere) as the small inside.
  return area > 0 ? closed.reverse() : closed;
});
